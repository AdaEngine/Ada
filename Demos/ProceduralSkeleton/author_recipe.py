"""Author the AdaScript recipe. Only stdlib; no mesh writer or 3D application.

Coordinates below use +Z for the front for readability; emitted AdaScript uses
the engine camera convention (front is -Z). All actual meshes are made by Ada.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
lines = ["// Generated by author_recipe.py; run directly through editor.model.generate.",
         "// Units: meters. Front: -Z. Static multipart study, not a skinned mesh.",
         "func part(m, p, parent, mat, name, x, y, z) {",
         "    m.parent(p, parent); m.paint(p, mat); m.name(p, name); m.place(p, x, y, z); return p;",
         "}", "func build(m) {"]
counter = 0


def n(value):
    return f"{value:.5f}".rstrip("0").rstrip(".") if value else "0"


def emit(text):
    lines.append("    " + text)


def group(name, parent=None):
    global counter
    counter += 1
    key = f"g{counter}"
    emit(f'var {key} = m.group(); m.name({key}, "{name}");')
    if parent:
        emit(f"m.parent({key}, {parent});")
    return key


def shape(expr, name, parent, mat, pos=(0, 0, 0), scale=None, rotation=None):
    global counter
    counter += 1
    key = f"p{counter}"
    x, y, z = pos
    emit(f'var {key} = part(m, {expr}, {parent}, {mat}, "{name}", {n(x)}, {n(y)}, {n(-z)});')
    if scale:
        emit(f"m.scale({key}, {', '.join(n(v) for v in scale)});")
    if rotation:
        emit(f"m.rotate({key}, {', '.join(n(v) for v in rotation)});")
    return key


def sphere(name, parent, mat, pos, scale, seg=8):
    return shape(f"m.sphere(1, {seg})", name, parent, mat, pos, scale)


def bone(name, parent, a, b, radius=.027, mat=1):
    delta = [b[0]-a[0], b[1]-a[1], -(b[2]-a[2])]
    length = math.sqrt(sum(v*v for v in delta))
    pitch = math.degrees(math.atan2(delta[2], delta[1]))
    roll = -math.degrees(math.asin(delta[0]/length))
    return shape(f"m.cylinder({n(radius*.85)}, {n(radius)}, {n(length)}, 7)",
                 name, parent, mat, tuple((x+y)/2 for x, y in zip(a, b)), rotation=(pitch, 0, roll))


def mesh(name, parent, mat, verts, tris):
    # Reflect Z and reverse winding to preserve outward normals.
    for x, y, z in verts:
        emit(f"m.vertex({n(x)}, {n(y)}, {n(-z)});")
    for a, b, c in tris:
        emit(f"m.triangle({a}, {c}, {b});")
    return shape("m.mesh()", name, parent, mat)


def front(name, parent, mat, verts, tris):
    fixed = []
    for a, b, c in tris:
        p, q, r = verts[a], verts[b], verts[c]
        cross_z = (q[0]-p[0])*(r[1]-p[1])-(q[1]-p[1])*(r[0]-p[0])
        fixed.append((a, b, c) if cross_z > 0 else (a, c, b))
    return mesh(name, parent, mat, verts, fixed)


def plate(name, parent, mat, polygon, front_z, back_z):
    count = len(polygon)
    area = sum(polygon[i][0]*polygon[(i+1)%count][1]-polygon[(i+1)%count][0]*polygon[i][1] for i in range(count))
    if area < 0:
        polygon = list(reversed(polygon))
    verts = [(x, y, front_z) for x, y in polygon] + [(x, y, back_z) for x, y in polygon]
    tris = []
    for i in range(1, count-1):
        tris += [(0, i, i+1), (count, count+i+1, count+i)]
    for i in range(count):
        j = (i+1)%count
        tris += [(i, count+i, j), (j, count+i, count+j)]
    return mesh(name, parent, mat, verts, tris)


def oval_ring(name, parent, mat, y, rx, rz, thickness, height, segments=16):
    # Lathe makes an actual hollow ring, rather than a solid disc hiding ribs.
    for r, yy in [(1, height/2), (1, -height/2), (1-thickness/rx, -height/2),
                  (1-thickness/rx, height/2), (1, height/2)]:
        emit(f"m.profile({n(r)}, {n(yy)});")
    return shape(f"m.lathe({segments})", name, parent, mat, (0, y, 0), (rx, 1, rz))


def build():
    materials = {
        0: (.73, .63, .43, 0, .85),    # bone shaded facets
        1: (.94, .83, .59, 0, .76),    # ivory
        2: (.12, .065, .025, 0, .95),  # cavity
        3: (.56, .25, .022, 0, .82),   # socket walls
        4: (1, .65, .015, 0, .35),     # luminous eye
        5: (.46, .16, .085, 0, .95),   # terracotta scarf
        6: (.24, .075, .038, 0, .95),  # folds, belt
        7: (.078, .067, .058, 0, .95), # shorts
        8: (.24, .32, .35, .6, .55),   # steel
        9: (.39, .17, .08, 0, .9),     # shield wood
        10: (.55, .64, .64, .5, .48),  # edge
    }
    for i, (r, g, b, metal, rough) in materials.items():
        emit(f"m.material({i}, {n(r)}, {n(g)}, {n(b)}); m.surface({i}, {n(metal)}, {n(rough)});")
    emit("m.emissive(4, 1, 0.65, 0.008);")
    root = group("Skeleton minion")
    head = group("Head", root)
    # Whole cranium shell: beveled perimeter, faceted sides and convex back.
    outline = [(-.22, 1.70), (.22, 1.70), (.46, 1.55),
               (.47, 1.25), (.37, 1.115), (.19, 1.06), (-.19, 1.06),
               (-.37, 1.115), (-.47, 1.25), (-.46, 1.55)]
    count = len(outline)
    verts = [(x, y, .265) for x, y in outline]
    verts += [(x*.92, 1.38+(y-1.38)*.95, -.19) for x, y in outline]
    verts += [(x*.57, 1.38+(y-1.38)*.66, -.29) for x, y in outline]
    verts.append((0, 1.38, -.31))
    tris = []
    # Outline is clockwise, side quads face out.
    for level in range(2):
        for i in range(count):
            j = (i+1)%count
            a, b = level*count+i, level*count+j
            c, d = a+count, b+count
            tris += [(a, b, c), (b, d, c)]
    for i in range(count):
        tris.append((2*count+i, 2*count+(i+1)%count, 3*count))
    mesh("Faceted cranium shell", head, 1, verts, tris)

    # Two open socket rings. Their side walls recede 11 cm into the skull.
    outer_left = [(-.22, 1.70), (0, 1.70), (0, 1.38),
                  (0, 1.10), (-.19, 1.06), (-.37, 1.115),
                  (-.47, 1.25), (-.46, 1.55)]
    for side in [-1, 1]:
        label = "Left" if side < 0 else "Right"
        outer = [(x*(-side), y, .265) for x, y in outer_left]
        cx, cy = side*.235, 1.365
        inner = [(cx+.155*math.sin(i*math.pi/4), cy+.16*math.cos(i*math.pi/4), .295) for i in range(8)]
        # Left inner sequence aligns clockwise top -> nose -> lower -> outer.
        if side > 0:
            inner = [(2*cx-x, y, z) for x, y, z in inner]
        v = outer+inner
        ts = []
        for i in range(8):
            j = (i+1)%8
            ts += [(i, j, 8+i), (j, 8+j, 8+i)]
        front(label+" orbital ivory rim", head, 1, v, ts)
        back = [(cx+(x-cx)*.72, cy+(y-cy)*.72, .17) for x, y, z in inner]
        # The wall normals face toward the socket center.
        wall = inner+back
        ts = []
        for i in range(8):
            j = (i+1)%8
            tri = (i, j, i+8)
            a,b,c = [wall[k] for k in tri]
            normal = ((b[1]-a[1])*(c[2]-a[2])-(b[2]-a[2])*(c[1]-a[1]),
                      (b[2]-a[2])*(c[0]-a[0])-(b[0]-a[0])*(c[2]-a[2]), 0)
            inward = (cx-(a[0]+b[0]+c[0])/3, cy-(a[1]+b[1]+c[1])/3)
            if normal[0]*inward[0]+normal[1]*inward[1] < 0:
                ts += [(i, i+8, j), (j, i+8, j+8)]
            else:
                ts += [(i, j, i+8), (j, j+8, i+8)]
        mesh(label+" recessed socket walls", head, 3, wall, ts)
        front(label+" socket shadow", head, 2, back, [(0, i, i+1) for i in range(1, 7)])
        sphere(label+" ember eye", head, 4, (cx, cy-.005, .205), (.061, .084, .043), 10)
    # Nose reads as a dark triangular recess with ivory bridge and lower bevel.
    plate("Nasal cavity", head, 2, [(-.065, 1.145), (.065, 1.145), (0, 1.285)], .288, .22)
    front("Nasal bevel", head, 0, [(-.075,1.135,.29), (-.065,1.145,.29),
          (0,1.17,.295), (.065,1.145,.29), (.075,1.135,.29)], [(0,1,2),(2,3,4)])
    for i, x in enumerate([-.27, -.135, 0, .135, .27]):
        plate(f"Upper tooth {i+1}", head, 1,
              [(x-.061,1.14), (x+.061,1.14), (x+.049,1.045), (x+.012,1.01), (x-.052,1.045)], .27, .12)
    jaw = group("Lower jaw", head)
    plate("Chin", jaw, 0, [(-.12,1.016), (.12,1.016), (.10,.945), (.045,.91), (-.07,.925)], .20, .07)
    for side in [-1, 1]:
        bone("Jaw hinge", jaw, (side*.13,.96,.11), (side*.24,1.10,.02), .032)
    plate("Chin light facet", jaw, 1, [(-.10,1.005), (.04,.98), (.065,.925), (-.06,.94)], .205, .20)

    torso = group("Torso", root)
    bone("Spine", torso, (0,.40,-.055), (0,1.01,-.055), .035, 0)
    sphere("Neck joint", torso, 0, (0,1.01,0), (.07,.06,.065))
    for level, (y, rx, rz) in enumerate([(.52,.23,.13), (.63,.255,.15), (.74,.27,.155), (.85,.26,.14)]):
        rib = group(f"Rib cage row {level+1}", torso)
        # U-shaped left and right ribs, with a gap in the sternum.
        for side in [-1, 1]:
            points = []
            for j in range(8):
                angle = -.5+j*(math.pi+.12)/7
                points.append((side*rx*math.sin(angle), y+.035*math.cos(angle), rz*math.cos(angle)))
            for j in range(len(points)-1):
                bone(f"Rib {level+1} segment {side} {j}", rib, points[j], points[j+1], .023)
    bone("Sternum", torso, (0,.53,.13), (0,.86,.14), .027, 0)
    for side in [-1,1]:
        bone("Clavicle", torso, (0,.90,0), (side*.31,.91,0), .033)
    scarf = group("Terracotta neckerchief", torso)
    plate("Scarf bib", scarf, 5, [(-.32,.94), (-.22,1.01), (0,.96), (.23,1.005), (.33,.93),
          (.24,.76), (.09,.665), (-.05,.65), (-.23,.76)], .205, .16)
    plate("Scarf left folded facet", scarf, 5, [(-.32,.94), (-.22,1.01), (-.04,.91), (.22,.82), (.09,.665), (-.05,.65)], .215, .21)
    fold = [(-.25,.925,.222), (-.12,.845,.225), (.015,.81,.225), (.15,.835,.222), (.25,.93,.219)]
    for i in range(4):
        bone("Scarf seam", scarf, fold[i], fold[i+1], .006, 6)
    plate("Back scarf tail", scarf, 5, [(-.04,.96), (.12,.93), (.18,.73), (.075,.78), (.02,.74)], -.115, -.16)
    oval_ring("Scarf collar", scarf, 5, .96, .14, .12, .028, .075)

    pelvis = group("Pelvis and belt", root)
    sphere("Dark shorts", pelvis, 7, (0,.395,0), (.245,.14,.13), 8)
    oval_ring("Leather belt", pelvis, 6, .475, .252, .155, .035, .075)
    # Buckle built from four bars, the leather remains visible through it.
    for name, pos, dimensions in [
        ("Buckle upper", (0,.511,.175), (.10,.016,.025)),
        ("Buckle lower", (0,.44,.175), (.10,.016,.025)),
        ("Buckle left", (-.047,.475,.175), (.016,.075,.025)),
        ("Buckle right", (.047,.475,.175), (.016,.075,.025)),
        ("Buckle tongue", (.007,.475,.19), (.065,.012,.012))]:
        shape("m.box("+", ".join(n(v) for v in dimensions)+")", name, pelvis, 8, pos)

    for side in [-1, 1]:
        leg = group("Left leg" if side < 0 else "Right leg", root)
        x = side*.14
        shape("m.cylinder(0.095, 0.087, 0.11, 8)", "Shorts leg", leg, 7, (x,.35,0))
        shape("m.cylinder(0.098, 0.098, 0.04, 8)", "Leather cuff", leg, 6, (x,.303,0))
        bone("Shin", leg, (x,.28,0), (x,.12,.015), .034)
        sphere("Knee", leg, 1, (x,.26,0), (.046,.05,.047))
        sphere("Ankle", leg, 0, (x,.12,.02), (.045,.045,.045))
        sphere("Chunky foot", leg, 1, (x,.055,.063), (.112,.055,.145))
        for j in [-1,1]:
            bone("Toe separation", leg, (x+j*.028,.058,.177), (x+j*.028,.085,.158), .004, 0)
        arm = group("Left arm" if side < 0 else "Right arm", root)
        shoulder = (side*.31,.91,0)
        elbow = (side*.49,.86,.012)
        sphere("Shoulder", arm, 0, shoulder, (.05,.055,.052))
        bone("Humerus", arm, shoulder, elbow, .029)
        sphere("Elbow", arm, 1, elbow, (.039,.042,.04))
        bone("Radius", arm, (side*.495,.88,.028), (side*.655,.88,.055), .019)
        bone("Ulna", arm, (side*.495,.84,0), (side*.655,.84,.025), .016)
        sphere("Hand", arm, 1, (side*.70,.86,.045), (.063,.063,.058))

    # Equipment kept as independent, named subassemblies. These are static props.
    equipment = group("Equipment", root)
    sword = group("Broken sword", equipment)
    # Hero holds sword on image-left, angled outward.
    plate("Notched blade", sword, 10, [(-.75,.90), (-.88,1.12), (-.98,1.28), (-.96,1.40),
          (-1.055,1.34), (-1.075,1.25), (-1.04,1.20), (-1.08,1.17), (-1.02,1.04), (-.87,.84)], .12, .075)
    bone("Blade fuller", sword, (-.81,.91,.124), (-1.015,1.30,.124), .009, 8)
    bone("Cross guard", sword, (-.88,.82,.10), (-.68,.94,.10), .032, 8)
    bone("Leather grip", sword, (-.77,.85,.10), (-.66,.67,.10), .036, 6)
    for i in range(3):
        bone("Grip wrap", sword, (-.775+i*.03,.835-i*.05,.135), (-.725+i*.03,.865-i*.05,.135), .009, 9)
    bone("Pommel", sword, (-.69,.67,.10), (-.625,.71,.10), .025, 8)
    shield = group("Round shield", equipment)
    # A vertical lathe ring, rotate +90 around X: model front is -Z.
    for r, y in [(.30,.027), (.30,-.027), (.255,-.027), (.255,.027), (.30,.027)]:
        emit(f"m.profile({n(r)}, {n(y)});")
    shape("m.lathe(12)", "Steel shield rim", shield, 10, (.80,.67,.145), rotation=(90,0,0))
    shape("m.cylinder(0.257, 0.257, 0.045, 12)", "Wood shield face", shield, 9, (.80,.67,.145), rotation=(90,0,0))
    sphere("Steel shield boss", shield, 8, (.80,.67,.195), (.095,.095,.048), 10)
    for xoff in [-.135,.135]:
        bone("Wood plank groove", shield, (.80+xoff,.49,.172), (.80+xoff,.85,.172), .005, 6)
    emit("}")


if __name__ == "__main__":
    build()
    target = ROOT / "Generators" / "Skeleton.ada"
    target.parent.mkdir(parents=True, exist_ok=True)
    source = "\n".join(lines)+"\n"
    if len(source.encode()) > 65536:
        raise RuntimeError("AdaScript source exceeds VM limit")
    target.write_text(source, encoding="utf-8")
    print(f"{target}: {len(source.encode())} bytes, {counter} nodes")
