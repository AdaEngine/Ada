import AdaScriptCompilerCore
import Foundation

private enum GeneratorError: Error, CustomStringConvertible {
    case invalidArguments

    var description: String {
        switch self {
        case .invalidArguments:
            "Usage: AdaScriptGeneratorTool --output <path> --root <target-directory> --module-name <name> [script.ada ...]"
        }
    }
}

@main
struct AdaScriptGeneratorTool {
    static func main() throws {
        let arguments = Array(CommandLine.arguments.dropFirst())
        guard arguments.count >= 6,
              arguments[0] == "--output",
              arguments[2] == "--root",
              arguments[4] == "--module-name" else {
            throw GeneratorError.invalidArguments
        }

        let outputURL = URL(fileURLWithPath: arguments[1], isDirectory: false)
        let rootURL = URL(fileURLWithPath: arguments[3], isDirectory: true)
        let moduleName = arguments[5]
        var remaining = Array(arguments.dropFirst(6))
        var librariesRoot: URL?
        if remaining.first == "--libraries-root", remaining.count >= 2 {
            librariesRoot = URL(fileURLWithPath: remaining[1], isDirectory: true)
            remaining.removeFirst(2)
        }
        let scriptURLs = remaining.map { URL(fileURLWithPath: $0, isDirectory: false) }
        let generatedSource = try makeGeneratedSource(
            moduleName: moduleName,
            scriptURLs: scriptURLs,
            rootURL: rootURL,
            librariesRoot: librariesRoot
        )

        try FileManager.default.createDirectory(
            at: outputURL.deletingLastPathComponent(),
            withIntermediateDirectories: true
        )

        if (try? String(contentsOf: outputURL, encoding: .utf8)) != generatedSource {
            try generatedSource.write(to: outputURL, atomically: true, encoding: .utf8)
        }
    }

    private static func makeGeneratedSource(
        moduleName: String,
        scriptURLs: [URL],
        rootURL: URL,
        librariesRoot: URL?
    ) throws -> String {
        var scripts = try scriptURLs.map { scriptURL in
            let source = try String(contentsOf: scriptURL, encoding: .utf8)
            return (path: relativePath(for: scriptURL, rootURL: rootURL), source: source)
        }
        if let librariesRoot {
            scripts += try AdaScriptLibraryLock.load(at: librariesRoot).loadSources(at: librariesRoot).map {
                (path: $0.path, source: $0.source)
            }
        }
        let compilerSources = scripts.map {
            AdaScriptCompilerSource(path: $0.path, source: $0.source)
        }
        let schemas = try AdaScriptSchemaParser.parse(sources: compilerSources)
        _ = try AdaScriptSchemaParser.parseNetworkCommands(sources: compilerSources)
        let scriptables = try AdaScriptSchemaParser.parseScriptables(sources: compilerSources)
        let views = try AdaScriptSchemaParser.parseViews(sources: compilerSources)
        let hasSystems = try !AdaScriptSchemaParser.parseSystemCapabilities(sources: compilerSources).isEmpty

        let scriptsDeclaration = embeddedSourcesDeclaration(scripts)
        let dataDeclarations = schemas
            .map { schemaDeclaration($0, moduleName: moduleName) }
            .joined(separator: "\n\n")
        let registrations = schemas
            .map { schemaRegistration($0, moduleName: moduleName) }
            .joined(separator: "\n        ")
        let scriptableRegistration = scriptableRegistration(scriptables)
        let viewAccessors = AdaScriptViewSourceGenerator.accessors(views, moduleName: moduleName)
        let viewRegistration = AdaScriptViewSourceGenerator.registration(views, moduleName: moduleName)
        let systemRegistration = systemRegistration(hasSystems: hasSystems, moduleName: moduleName)

        let multiplayerImport = schemas.contains(where: { $0.replication != nil }) ? "import AdaMultiplayer" : ""
        return """
        // This file is generated by AdaScriptBuildPlugin. Do not edit.
        import AdaEngine
        \(multiplayerImport)

        \(dataDeclarations)

        \(viewAccessors)

        struct AdaScriptPluginsGenerated: Plugin {
            @MainActor
            func setup(in app: borrowing AppWorlds) {
                \(registrations)
                guard !Self.sources.isEmpty else { return }
                do {
                    \(scriptableRegistration)
                    \(viewRegistration)
                    \(systemRegistration)
                } catch {
                    print("AdaEngine: failed to load Ada Script module \\(Self.moduleName): \\(error)")
                }
            }

            private static let moduleName = \(swiftStringLiteral(moduleName))
            private static let sources: [AdaScriptSource] = \(scriptsDeclaration)
        }

        """
    }

    private static func embeddedSourcesDeclaration(_ scripts: [(path: String, source: String)]) -> String {
        let entries = scripts
            .map { script in
                "        AdaScriptSource(path: \(swiftStringLiteral(script.path)), source: \(swiftStringLiteral(script.source)))"
            }
            .joined(separator: ",\n")
        return entries.isEmpty ? "[]" : "[\n\(entries)\n    ]"
    }

    private static func scriptableRegistration(_ scriptables: [AdaScriptableSchema]) -> String {
        guard !scriptables.isEmpty else {
            return ""
        }
        let declarations = scriptables
            .map(scriptableSchemaDeclaration)
            .joined(separator: ",\n")
        return """
                try AdaScriptObjectRegistration.register(
                    schemas: [
        \(declarations)
                    ],
                    sources: Self.sources,
                    moduleName: Self.moduleName
                )
        """
    }

    private static func systemRegistration(hasSystems: Bool, moduleName: String) -> String {
        guard hasSystems else {
            return ""
        }
        return """
                app.addPlugin(
                    try AdaScriptPlugin(
                        sources: Self.sources,
                        name: \(swiftStringLiteral(moduleName))
                    )
                )
        """
    }

    private static func scriptableSchemaDeclaration(_ schema: AdaScriptableSchema) -> String {
        let aliases = schema.aliases.map(swiftStringLiteral).joined(separator: ", ")
        let bindings = schema.bindings
            .map(scriptableBindingDeclaration)
            .joined(separator: ", ")
        let fields = schema.fields
            .map { field in
                "\(swiftStringLiteral(field.name)): \(reflectedFieldValue(field.defaultValue))"
            }
            .joined(separator: ", ")
        return """
                        AdaScriptObjectSchema(
                            identifier: \(swiftStringLiteral(schema.id)),
                            className: \(swiftStringLiteral(schema.name)),
                            version: \(schema.version),
                            aliases: [\(aliases)],
                            bindings: [\(bindings)],
                            fields: [\(fields)]
                        )
        """
    }

    private static func scriptableBindingDeclaration(_ binding: AdaScriptableBinding) -> String {
        let kind: String
        switch binding.kind {
        case .component(let required):
            kind = ".component(required: \(required))"
        case .resource(let optional):
            kind = ".resource(optional: \(optional))"
        }
        return """
        AdaScriptObjectBinding(
            kind: \(kind),
            propertyName: \(swiftStringLiteral(binding.propertyName)),
            typeName: \(swiftStringLiteral(binding.typeName))
        )
        """
    }

    private static func reflectedFieldValue(_ value: AdaScriptSchemaField.Value) -> String {
        switch value {
        case .bool(let value): ".bool(\(value))"
        case .double(let value): ".double(\(value))"
        case .int(let value): ".int(\(value))"
        case .string(let value): ".string(\(swiftStringLiteral(value)))"
        }
    }

    private static func schemaDeclaration(_ schema: AdaScriptDataSchema, moduleName: String) -> String {
        let typeName = generatedTypeName(schema, moduleName: moduleName)
        let fields = schema.fields
            .map { field in
                "    var \(field.name): \(swiftType(field.defaultValue)) = \(swiftDefault(field.defaultValue))"
            }
            .joined(separator: "\n")
        switch schema.kind {
        case .component:
            if let replication = schema.replication {
                let codingKeys = schema.fields.compactMap { field -> String? in
                    guard let network = field.network else {
                        return nil
                    }
                    return "        case \(field.name) = \(swiftStringLiteral(String(network.tag)))"
                }.joined(separator: "\n")
                return """
                @Component(required: [ReplicatedEntity.self])
                struct \(typeName): Codable, Sendable {
                \(fields)

                    private enum CodingKeys: String, CodingKey {
                \(codingKeys)
                    }
                }

                extension \(typeName): NetworkReplicatedComponent {
                    static var networkDescriptor: NetworkTypeDescriptor {
                        NetworkTypeDescriptor(
                            typeID: \(swiftStringLiteral(schema.id)),
                            version: \(replication.version),
                            kind: .component,
                            authority: \(networkAuthority(replication.authority)),
                            visibility: \(networkVisibility(replication.visibility)),
                            fields: [
                \(networkFieldDescriptors(schema))
                            ]
                        )
                    }
                }
                """
            }
            return """
            @Component
            struct \(typeName): Codable, Sendable {
            \(fields)
            }
            """
        case .resource:
            return """
            struct \(typeName): Codable, Resource, Sendable {
            \(fields)
            }
            """
        }
    }

    private static func schemaRegistration(_ schema: AdaScriptDataSchema, moduleName: String) -> String {
        let typeName = generatedTypeName(schema, moduleName: moduleName)
        let names = "[\(swiftStringLiteral(schema.name)), \(swiftStringLiteral(schema.id))]"
        switch schema.kind {
        case .component:
            let typeRegistration = "RuntimeTypeRegistry.registerComponent(\(typeName).self, names: \(names), makeDefault: { \(typeName)() })"
            if schema.replication != nil {
                return "app.registerReplicatedComponent(\(typeName).self)\n        \(typeRegistration)"
            }
            return typeRegistration
        case .resource(let autoInsert):
            let fieldDescriptors = resourceFieldDescriptors(schema, typeName: typeName)
            let registration = """
            RuntimeTypeRegistry.registerResource(\(typeName).self, names: \(names))
                    RuntimeResourceReflectionRegistry.register(\(typeName).self, fields: [
            \(fieldDescriptors)
                    ])
            """
            return autoInsert ? "\(registration)\n        app.main.insertResource(\(typeName)())" : registration
        }
    }

    private static func resourceFieldDescriptors(_ schema: AdaScriptDataSchema, typeName: String) -> String {
        schema.fields
            .map { field in
                let fieldType = swiftType(field.defaultValue)
                return """
                    unsafe ReflectedComponentField(
                        key: \(swiftStringLiteral(field.name)),
                        label: \(swiftStringLiteral(field.name)),
                        kind: ComponentReflection.kind(for: \(fieldType).self),
                        isWritable: ComponentReflection.isWritable(\(fieldType).self),
                        accepts: { ComponentReflection.accepts($0, for: \(fieldType).self) },
                        read: { _ in nil },
                        write: { _, _ in nil },
                        readPointer: { pointer in
                            let resource = unsafe pointer.assumingMemoryBound(to: \(typeName).self)
                            return ComponentReflection.read(unsafe resource.pointee.\(field.name))
                        },
                        writePointer: { pointer, value in
                            let resource = unsafe pointer.assumingMemoryBound(to: \(typeName).self)
                            return unsafe ComponentReflection.write(value, to: &resource.pointee.\(field.name))
                        }
                    )
                """
            }
            .joined(separator: ",\n")
    }

    private static func networkFieldDescriptors(_ schema: AdaScriptDataSchema) -> String {
        schema.fields.compactMap { field -> String? in
            guard let network = field.network else {
                return nil
            }
            return """
                                NetworkFieldDescriptor(
                                    tag: \(network.tag),
                                    wireType: \(networkWireType(field.defaultValue)),
                                    replication: \(networkReplicationMode(network.mode)),
                                    interpolation: \(networkInterpolationMode(network.interpolation))
                                )
            """
        }.joined(separator: ",\n")
    }

    private static func networkAuthority(_ value: String) -> String {
        value == "host" ? ".host" : ".anyPeer"
    }

    private static func networkVisibility(_: String) -> String {
        ".allPeers"
    }

    private static func networkReplicationMode(_ value: String) -> String {
        switch value {
        case "latest": ".latest"
        case "initial_only": ".initialOnly"
        default: ".state"
        }
    }

    private static func networkInterpolationMode(_ value: String) -> String {
        switch value {
        case "linear": ".linear"
        case "custom": ".custom"
        default: ".none"
        }
    }

    private static func networkWireType(_ value: AdaScriptSchemaField.Value) -> String {
        switch value {
        case .bool: ".bool"
        case .double: ".floatingPoint"
        case .int: ".signedInteger"
        case .string: ".string"
        }
    }

    private static func generatedTypeName(_ schema: AdaScriptDataSchema, moduleName: String) -> String {
        "__AdaScript_\(swiftIdentifier(moduleName))_\(swiftIdentifier(schema.name))"
    }

    private static func swiftIdentifier(_ value: String) -> String {
        let scalars = value.unicodeScalars.map { scalar -> String in
            CharacterSet.alphanumerics.contains(scalar) || scalar == "_" ? String(scalar) : "_"
        }
        let result = scalars.joined()
        return result.first?.isNumber == true ? "_\(result)" : result
    }

    private static func swiftType(_ value: AdaScriptSchemaField.Value) -> String {
        switch value {
        case .bool: "Bool"
        case .double: "Double"
        case .int: "Int64"
        case .string: "String"
        }
    }

    private static func swiftDefault(_ value: AdaScriptSchemaField.Value) -> String {
        switch value {
        case .bool(let value): String(value)
        case .double(let value): String(value)
        case .int(let value): String(value)
        case .string(let value): swiftStringLiteral(value)
        }
    }

    private static func relativePath(for fileURL: URL, rootURL: URL) -> String {
        let filePath = fileURL.standardizedFileURL.path
        let rootPath = rootURL.standardizedFileURL.path
        let rootPrefix = rootPath.hasSuffix("/") ? rootPath : rootPath + "/"
        guard filePath.hasPrefix(rootPrefix) else {
            return fileURL.lastPathComponent
        }
        return String(filePath.dropFirst(rootPrefix.count))
    }

    private static func swiftStringLiteral(_ value: String) -> String {
        var result = "\""
        for scalar in value.unicodeScalars {
            switch scalar.value {
            case 0x22:
                result += "\\\""
            case 0x5C:
                result += "\\\\"
            case 0x0A:
                result += "\\n"
            case 0x0D:
                result += "\\r"
            case 0x09:
                result += "\\t"
            case 0x20...0x7E:
                result.unicodeScalars.append(scalar)
            default:
                result += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
            }
        }
        result += "\""
        return result
    }
}
